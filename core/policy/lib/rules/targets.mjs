// What may be created, changed or deleted. Shared by the file tools and by Bash writers
// (redirections, tee, cp, mv, sed -i, rm, ...).
import { deny, ask } from '../decision.mjs';
import { git, readState, linkedPath } from '../context.mjs';
import { relTo, matchAny, isSecretPath, isLockFile, isTfState } from '../paths.mjs';
import { isApproved } from '../approvals.mjs';

// A migration file that already exists on the base branch (dev) may have been applied somewhere.
function appliedMigration(rel, root, ctx) {
  const main = ctx.config.branches.base;
  const base = git(root, ['rev-parse', '--verify', '-q', `origin/${main}`]).ok ? `origin/${main}` : main;
  return git(root, ['cat-file', '-e', `${base}:${rel}`]).ok;
}

export function writeFindings(file, ctx, how = 'Changing') {
  const cfg = ctx.config;
  const abs = linkedPath(file, ctx);
  const root = relTo(abs, ctx.root) !== null ? ctx.root : (relTo(abs, ctx.mainRoot) !== null ? ctx.mainRoot : null);
  const rel = root ? relTo(abs, root) : null;
  const name = rel ?? abs;

  const isConfig = rel === cfg.kit.configPath || rel === '.forge/project.json';
  if (relTo(abs, ctx.stateDir) !== null || (rel !== null && (rel === '.git' || rel.startsWith('.git/'))) || (!isConfig && matchAny(cfg.kit.codePaths, rel))) {
    return [deny('kit:protected', `${how} ${name} is not allowed: it is part of the safety layer (hooks, settings, approvals, git internals).`)];
  }
  if (rel !== null && rel.startsWith('.claude/') && readState(ctx, 'sync-manifest.json', { files: {} }).files[rel]) {
    return [deny('kit:generated', `${rel} is generated by forge sync. Change the role, skill or command in the team repo (.forge/project/kit/) and run forge sync.`)];
  }
  if (isSecretPath(abs, cfg, ctx.home)) return [deny('secrets:write', `${how} secret files is not allowed (${name}). Put placeholder names in .env.example instead.`)];
  if (isTfState(abs)) return [deny('infra:tfstate', `Terraform state is never changed by hand (${name}).`)];
  if (isLockFile(abs)) return [deny('deps:lockfile', `Lock files change only through the package manager (${name}).`)];
  if (rel === null) return [];
  if (matchAny(cfg.paths.generated, rel)) return [deny('generated', `${rel} is generated code. Regenerate it with the project's generate command; never hand-edit it.`)];
  if (matchAny(cfg.paths.protected, rel)) return [deny('source-of-truth', `${rel} is a source of truth owned by a human. Raise the conflict in your plan or a tracker task instead.`)];
  if (matchAny(cfg.paths.migrations, rel) && appliedMigration(rel, root, ctx)) {
    return [deny('db:applied-migration', `${rel} is already on ${cfg.branches.base} and may be applied somewhere. Add a new migration instead.`)];
  }

  const out = [];
  if (isConfig) out.push(ask('repo:config', `${how} the project policy config changes the safety rules.`));
  if (matchAny(cfg.paths.ci, rel)) out.push(ask('repo:ci', `${how} ${rel} changes what the pipeline checks and deploys.`));
  if (matchAny(cfg.paths.contract, rel) && !isApproved(ctx, 'contract')) {
    out.push(ask('gate:contract', `${rel} is the API contract. The lead puts a checked draft on its own branch with forge api apply <draft> (decision 148); approving allows contract edits on branch ${ctx.branch() ?? '(detached HEAD)'}.`, { gate: 'contract', record: true }));
  }
  // Once per branch (decision 148): the bootstrap's setup copies every accepted ADR at once.
  if (matchAny(cfg.paths.adr, rel) && !isApproved(ctx, 'architecture')) out.push(ask('gate:architecture', `${rel} records an architecture or stack decision, which a human approves; approving allows ADR edits on branch ${ctx.branch() ?? '(detached HEAD)'}.`, { gate: 'architecture', record: true }));
  if (rel.startsWith('.claude/')) out.push(ask('repo:agent-config', `${how} agent configuration (${rel}).`));
  if (rel.startsWith('.forge/project/kit/')) out.push(ask('repo:agent-config', `${how} the project's kit overrides (${rel}) changes the agents, skills or rules for everyone on the project.`));
  if (/(^|\/)\.gitleaks(ignore|\.toml)$/.test(rel)) out.push(ask('secrets:allowlist', `${how} ${rel} changes which secrets the scanner lets through.`));
  if (matchAny(cfg.paths.sensitive, rel) && !isApproved(ctx, 'security')) {
    out.push(ask('gate:security', `${rel} is security-sensitive (auth, permissions, payments or personal data). Approving allows such changes on branch ${ctx.branch() ?? '(detached HEAD)'}.`, { gate: 'security', record: true }));
  }
  return out;
}
